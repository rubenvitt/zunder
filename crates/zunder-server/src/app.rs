//! Application service: the single entry point for everything that reads or
//! changes data. HTTP handlers, MCP tools and the Timing bridge all go
//! through [`App`], so validation, the op log, the in-memory state and the
//! change notifications stay consistent.
//!
//! Concurrency model (correctness first):
//!
//! - One writer connection behind a mutex; every write runs in
//!   `spawn_blocking` while holding it. Validation, persistence and applying
//!   to the in-memory state happen under this lock, so no two pushes
//!   interleave.
//! - One reader connection (WAL allows reading while writing) for pulls,
//!   history and lookups.
//! - The materialized [`State`] plus its cursor live in an `RwLock`; readers
//!   always see a state together with the cursor it corresponds to.

